// Builds the outputs of the design tokens in memory: the single place that
// knows Style Dictionary. `build-tokens.mjs` writes what this returns, and the
// tests compare it with the committed files, so a hand edit of a generated
// file cannot survive. Knows nothing about the CSS that uses the tokens.
//
// One CSS file holds the base roles on :root and, after them, one block per
// mode in tokens/modes/ on :root[data-mode="<name>"], with only the roles that
// mode redefines.

import StyleDictionary from 'style-dictionary';
import { readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Style Dictionary globs its sources, and a glob wants forward slashes even
// on Windows.
const glob = (...parts) => path.join(root, ...parts).replaceAll('\\', '/');
const baseTokens = glob('tokens', '*.tokens.json');

const header = [
  'Generated by scripts/build-tokens.mjs from tokens/*.tokens.json and tokens/modes/.',
  'Do not edit: change the tokens and run `npm run tokens`.',
];

const hooks = {
  fileHeaders: { kanshi: () => header },
  transforms: {
    // TODO: drop when style-dictionary is raised to 5.7.0 or later, which
    // reads DTCG 2025.10 durations itself; 5.6.1 prints "[object Object]".
    'kanshi/duration': {
      type: 'value',
      filter: (token) => token.$type === 'duration' && typeof token.$value === 'object',
      transform: (token) => `${token.$value.value}${token.$value.unit}`,
    },
  },
};

// The palette stays in the token source for tools that read it, but not in
// the CSS: components reach colors only through roles.
const notPalette = (token) => token.path[0] !== 'palette';

async function css({ include = [], source, selector, filter, showHeader }) {
  const dictionary = new StyleDictionary({
    include,
    source,
    usesDtcg: true,
    log: { verbosity: 'silent', warnings: 'error' },
    hooks,
    platforms: {
      css: {
        transformGroup: 'css',
        transforms: ['kanshi/duration'],
        prefix: 'k',
        files: [
          {
            destination: 'tokens.css',
            format: 'css/variables',
            filter,
            options: { selector, outputReferences: false, fileHeader: 'kanshi', showFileHeader: showHeader },
          },
        ],
      },
    },
  });
  const [file] = await dictionary.formatPlatform('css');
  return String(file.output);
}

async function modeNames() {
  const names = await readdir(path.join(root, 'tokens', 'modes'));
  return names.filter((name) => name.endsWith('.tokens.json')).map((name) => name.replace('.tokens.json', '')).sort();
}

/** @returns {Promise<{ destination: string, output: string }[]>} paths relative to the repo root */
export async function buildTokenFiles() {
  const blocks = [await css({ source: [baseTokens], selector: ':root', filter: notPalette, showHeader: true })];
  for (const mode of await modeNames()) {
    blocks.push(
      await css({
        include: [baseTokens],
        source: [glob('tokens', 'modes', `${mode}.tokens.json`)],
        selector: `:root[data-mode="${mode}"]`,
        // Only what the mode itself redefines: the rest comes from :root.
        filter: (token) => token.isSource && notPalette(token),
        showHeader: false,
      }),
    );
  }
  return [{ destination: 'src/tokens.css', output: blocks.join('\n') }];
}

export { root };
